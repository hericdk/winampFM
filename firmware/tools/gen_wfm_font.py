def emit(name, glyphs, h):
    widths, rows = [], []
    for c in range(32, 96):
        g = glyphs.get(chr(c), glyphs['?'])
        r = g.split('|')
        assert len(r) == h, (name, chr(c))
        w = len(r[0])
        assert all(len(x) == w for x in r) and w <= 8, (name, chr(c))
        widths.append(w)
        rows.append([sum(1 << (7 - i) for i, ch in enumerate(x) if ch == '#') for x in r])
    out = [f'#define {name}_H {h}',
           f'static const uint8_t {name}_W[64] = {{{", ".join(map(str, widths))}}};',
           f'static const uint8_t {name}_ROWS[64][{h}] = {{']
    out += ['    {' + ', '.join(f'0x{b:02x}' for b in r) + '},' for r in rows]
    out.append('};')
    return '\n'.join(out)


def main():
    out = sys.argv[1]
    txt = '/* generated by tools/gen_wfm_font.py: do not edit */\n#pragma once\n' + emit('WFS', S, 5) + '\n' + emit('WFM', M, 7) + '\n'
    with open(out, 'w') as f:
        f.write(txt)


if __name__ == '__main__':
    main()
