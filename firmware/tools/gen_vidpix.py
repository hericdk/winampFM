#!/usr/bin/env python3
"""winampFM: assets/vidpix/<name>/NN.png (palette PNGs) -> build/gen/wfm_vidpix.h. Frame 0 whole, the others as changes over the one
before; a byte = colour << 4 | (run - 1) (15: a byte more, the run - 16), colour 15 = unchanged (so 15 colours at most)."""
import os, sys
from PIL import Image

ORDER = ['STUDY', 'RACCOON']   # (the whole screen's order: ui_winamp.c GV_*)
FPS = {'STUDY': 6, 'RACCOON': 7}   # its frames a second at 120 BPM

def runs(seq):
    """colour << 4 | (run - 1) for runs of 1..15; colour << 4 | 15 then a byte for runs of 16..271"""
    out, i = [], 0
    while i < len(seq):
        j = i
        while j < len(seq) and seq[j] == seq[i] and j - i < 271: j += 1
        r = j - i
        if r <= 15: out.append(seq[i] << 4 | (r - 1))
        else: out += [seq[i] << 4 | 15, r - 16]
        i = j
    return out

def main(root, outp):
    L = ['/* generated by tools/gen_vidpix.py: videos as chunky pixel art (local tests) */', '#pragma once',
         'typedef struct { const char *name; uint8_t w, h, nf, fps; const uint16_t *pal; const uint8_t *data; const uint32_t *off; } vp_clip_t;']
    names, total = [], 0
    for n in ORDER:
        d = os.path.join(root, 'assets', 'vidpix', n)
        fs = sorted(f for f in os.listdir(d) if f.endswith('.png')) if os.path.isdir(d) else []
        if not fs: continue
        ims = [Image.open(os.path.join(d, f)) for f in fs]
        w, h = ims[0].size
        p = ims[0].getpalette()[:45]
        cols = max(max(im.getdata()) for im in ims) + 1
        pal = [((p[3 * i] >> 3) << 11) | ((p[3 * i + 1] >> 2) << 5) | (p[3 * i + 2] >> 3) for i in range(cols)]
        data, offs, prev = [], [], None
        for im in ims:
            cur = list(im.getdata())
            seq = cur if prev is None else [15 if c == q else c for c, q in zip(cur, prev)]
            offs.append(len(data)); data += runs(seq); prev = cur
        L.append(f'static const uint16_t VP_{n}_PAL[{len(pal)}] = {{{", ".join(str(v) for v in pal)}}};')
        L.append(f'static const uint32_t VP_{n}_OFF[{len(offs)}] = {{{", ".join(str(v) for v in offs)}}};')
        L.append(f'static const uint8_t VP_{n}_DATA[{len(data)}] = {{')
        for i in range(0, len(data), 32): L.append('    ' + ', '.join(str(v) for v in data[i:i + 32]) + ',')
        L.append('};')
        names.append((n, w, h, len(ims))); total += len(data) + 4 * len(offs) + 2 * len(pal)
    L.append(f'#define VP_N {len(names)}')
    L.append('static const vp_clip_t VP_CLIPS[VP_N > 0 ? VP_N : 1] = {' + ', '.join(f'{{"{n}", {w}, {h}, {nf}, {FPS.get(n, 4)}, VP_{n}_PAL, VP_{n}_DATA, VP_{n}_OFF}}' for n, w, h, nf in names) + '};')
    open(outp, 'w').write('\n'.join(L) + '\n')
    print(f'vidpix: {len(names)} clips, {total} B')

if __name__ == '__main__':
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    main(root, sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, 'build', 'gen', 'wfm_vidpix.h'))
